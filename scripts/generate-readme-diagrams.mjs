const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  console.error('Usage: node scripts/generate-readme-diagrams.mjs [--check]');
  process.exit(2);
}
const path = new URL('../docs/images/slp-overview.svg', import.meta.url);
const svg = render();
if (args[0] === '--check') {
  let saved = null;
  try { saved = readFileSync(path, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (saved !== svg) { console.error('slp-overview.svg is stale'); process.exit(1); }
} else writeFileSync(path, svg);
console.log(args[0] === '--check' ? 'README overview is current.' : 'Generated README overview.');
